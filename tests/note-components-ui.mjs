/** Note picker, native Files tags, and expanded editor contracts on isolated data. */
import assert from 'node:assert/strict'
import {chromium} from 'playwright'
import {fileURLToPath} from 'node:url'

const uiUrl=name=>'/@fs/'+fileURLToPath(import.meta.resolve(`@nextspace/ui/${name}`)).replaceAll('\\','/')

const browser=await chromium.launch({headless:true,channel:'msedge'})
const page=await browser.newPage({viewport:{width:1200,height:1000}})
const errors=[],checks=[]
page.on('pageerror',error=>errors.push(error.message))
page.setDefaultTimeout(10000)
await page.route('**/notes-component-harness',route=>route.fulfill({contentType:'text/html',body:`<!doctype html><html><head><link rel="stylesheet" href="${uiUrl('style.css')}"/></head><body><div id="harness" style="max-width:900px;margin:30px auto;padding:25px;background:var(--surface)"></div><script type="module">
import {createApp,h,reactive} from '/node_modules/.vite/deps/vue.js'
import Picker from '${uiUrl('components/NoteLinkPicker.vue')}'
import Tags from '${uiUrl('components/NoteTagsEditor.vue')}'
import Editor from '${uiUrl('components/NoteEditorDialog.vue')}'
import Files from '${uiUrl('components/CloudFilePicker.vue')}'
const note=(id,title)=>({id,title,kind:'note',source:'notes',collectionTitle:'Research',body:'Notes for the project',remote:{category:'Research'}})
const state=reactive({scene:'picker',record:{id:'work',title:'Prepare delivery',kind:'task',source:'tasks'},notes:[note('one','Delivery brief'),note('two','Client notes'),note('three','Already linked')],relations:[{id:'link',type:'reference',fromId:'work',toId:'three'}],linkedIds:[],createdNote:undefined,adds:[],creates:[],dirty:false,tagSaves:[],tagDiscards:0,failTags:false,tags:[{id:'1',title:'Team',assignable:false}],tagOptions:[{id:'1',title:'Team',assignable:false},{id:'2',title:'Freelance',assignable:true}],draft:{id:'one',title:'Delivery brief',content:'# Brief\\n\\nStart here.',category:'Research',etag:'v1'},collapsed:false,saved:false,attached:[],attachCalls:[],failFile:true,fileDone:false,fileChanges:0,fileBusy:false})
window.noteHarness=state
const fileApi={listFiles:async({path})=>({path:path||'/',files:path==='/Notes'?[{id:'11',name:'Reference.md',path:'/Notes/Reference.md',directory:false,size:2000}]:[{id:'10',name:'Notes',path:'/Notes',directory:true},{id:'12',name:'Brief.pdf',path:'/Brief.pdf',directory:false,size:1048576}]}),attachDeckFile:async({path})=>{state.attachCalls.push(path);if(path==='/Notes/Reference.md'&&state.failFile)throw new Error('Fixture attachment failed');state.attached.push(path);return {attachments:[]}}}
createApp({setup(){return()=>state.scene==='picker'?h(Picker,{record:state.record,records:state.notes,relations:state.relations,linkedIds:state.linkedIds,createdNote:state.createdNote,canCreate:true,categories:['Research','Freelance'],creationSuggestion:'Freelance',onAdd:ids=>state.adds.push(ids),onCreate:input=>state.creates.push(input),onDirty:value=>state.dirty=value}):state.scene==='tags'?h(Tags,{tags:state.tags,options:state.tagOptions,suggestions:[{id:'suggestion',title:'Freelance'}],saveChanges:async tags=>{state.tagSaves.push(tags);if(state.failTags)return false;state.tags=tags.map(tag=>({...tag,id:tag.id.startsWith('new:')?'created':tag.id}));return true},onDirty:value=>state.dirty=value,onDiscard:()=>state.tagDiscards++}):state.scene==='files'?h(Files,{record:state.record,api:fileApi,canWrite:true,busy:state.fileBusy,onBusy:value=>state.fileBusy=value,onDirty:value=>state.dirty=value,onChanged:()=>state.fileChanges++,onDone:()=>state.fileDone=true}):h(Editor,{modelValue:state.draft,categories:['Research','Freelance'],'onUpdate:modelValue':value=>state.draft=value,onCollapse:()=>state.collapsed=true,onSave:()=>state.saved=true})}}).mount('#harness')
</script></body></html>`}))

try{
  await page.goto((process.env.NEXTSPACE_TEST_URL||'http://127.0.0.1:5173')+'/notes-component-harness')
  await page.getByRole('heading',{name:'Attach to this work'}).waitFor()
  assert.equal(await page.getByRole('checkbox',{name:'Already linked',exact:true}).isDisabled(),true)
  await page.getByRole('checkbox',{name:'Delivery brief',exact:true}).check()
  await page.getByRole('checkbox',{name:'Client notes',exact:true}).check()
  await page.getByLabel('Find notes and pages').fill('Delivery')
  await page.getByRole('button',{name:'Link 2 notes',exact:true}).click()
  assert.deepEqual(await page.evaluate(()=>window.noteHarness.adds.at(-1)),['one','two'])
  await page.evaluate(()=>window.noteHarness.linkedIds=['one'])
  await page.getByRole('button',{name:'Link 1 note',exact:true}).click()
  assert.deepEqual(await page.evaluate(()=>window.noteHarness.adds.at(-1)),['two'])
  checks.push('Multiple selection survives search, existing links are disabled, and partial successes leave only remaining notes selected')

  await page.getByRole('tab',{name:'Create a note',exact:true}).click()
  await page.getByLabel('New note title').fill('Production notes')
  assert.equal(await page.getByRole('button',{name:/^Suggested category:/}).count(),0)
  await page.getByLabel('New note folder',{exact:true}).fill('Freelance')
  await page.getByRole('button',{name:'Create note',exact:true}).click()
  assert.deepEqual(await page.evaluate(()=>window.noteHarness.creates.at(-1)),{title:'Production notes',content:'',category:'Freelance'})
  await page.evaluate(()=>{window.noteHarness.createdNote={id:'new-note',kind:'note',source:'notes',title:'Production notes',body:'',collectionTitle:'Freelance'}})
  await page.getByRole('checkbox',{name:'Production notes',exact:true}).waitFor()
  assert.equal(await page.getByRole('checkbox',{name:'Production notes',exact:true}).isChecked(),true)
  await page.getByRole('button',{name:'Link 2 notes',exact:true}).click()
  assert.deepEqual(await page.evaluate(()=>window.noteHarness.adds.at(-1)),['two','new-note'])
  assert.equal(await page.evaluate(()=>window.noteHarness.creates.length),1)
  checks.push('New native note receipt is selected alongside previous choices, without creating another note when links are retried')
  await page.evaluate(()=>window.noteHarness.linkedIds=['one','new-note'])
  await page.getByRole('tab',{name:'Create a note',exact:true}).click()
  await page.getByLabel('New note title').fill('Hidden draft')
  await page.getByRole('tab',{name:/^Existing notes/}).click()
  assert.equal(await page.evaluate(()=>window.noteHarness.dirty),true,'A hidden create form must still protect its draft')
  assert.equal(await page.getByRole('button',{name:'Link 1 note',exact:true}).isDisabled(),true,'Linking existing notes must not silently discard a hidden new-note draft')
  await page.getByRole('tab',{name:'Create a note',exact:true}).click()
  assert.equal(await page.getByLabel('New note title').inputValue(),'Hidden draft')

  await page.evaluate(()=>window.noteHarness.scene='tags')
  await page.getByRole('button',{name:'Edit note tags',exact:true}).click()
  assert.equal(await page.getByRole('checkbox',{name:'Team Managed',exact:true}).isDisabled(),true)
  await page.getByRole('checkbox',{name:'Freelance',exact:true}).check()
  await page.getByLabel('Find note tags').fill('Delivery')
  await page.getByRole('button',{name:'Create “Delivery”',exact:true}).click()
  assert.equal(await page.getByLabel('Find note tags').evaluate(element=>element===document.activeElement),true,'Creating a tag returns focus to the picker when the create button disappears')
  await page.getByLabel('Find note tags').press('Escape')
  await page.getByRole('dialog',{name:'Note tags',exact:true}).waitFor({state:'hidden'})
  assert.equal(await page.evaluate(()=>window.noteHarness.tagSaves.length),0,'Escape closes the picker without saving the pending draft')
  await page.getByRole('button',{name:'Edit note tags',exact:true}).click()
  await page.evaluate(()=>window.noteHarness.failTags=true)
  await page.getByRole('button',{name:'Done',exact:true}).click()
  await page.getByRole('alert').waitFor()
  assert.equal(await page.evaluate(()=>window.noteHarness.dirty),true)
  assert.deepEqual(await page.evaluate(()=>window.noteHarness.tagSaves.at(-1).map(tag=>tag.title)),['Team','Freelance','Delivery'])
  await page.mouse.click(5,5)
  assert.equal(await page.evaluate(()=>window.noteHarness.tagSaves.length),1,'Clicking away must not retry a failed native tag save')
  await page.evaluate(()=>window.noteHarness.failTags=false)
  await page.getByRole('button',{name:'Retry',exact:true}).click()
  await page.getByRole('dialog',{name:'Note tags',exact:true}).waitFor({state:'hidden'})
  assert.equal(await page.evaluate(()=>window.noteHarness.dirty),false)
  assert.deepEqual(await page.evaluate(()=>window.noteHarness.tags.map(tag=>tag.title)),['Team','Freelance','Delivery'])
  await page.getByRole('button',{name:'Edit note tags',exact:true}).click()
  await page.getByRole('checkbox',{name:'Freelance',exact:true}).uncheck()
  await page.evaluate(()=>window.noteHarness.failTags=true)
  await page.getByRole('button',{name:'Done',exact:true}).click()
  await page.getByRole('alert').waitFor()
  await page.getByRole('button',{name:'Cancel',exact:true}).click()
  assert.equal(await page.evaluate(()=>window.noteHarness.tagDiscards),1,'Explicitly cancelling a failed draft releases the parent failed edit')
  assert.equal(await page.evaluate(()=>window.noteHarness.dirty),false)
  checks.push('Native tags support multiple selection and creation, preserve managed tags, and keep a failed draft available for retry')

  const existingLongName='Existing '+ 'é'.repeat(35)
  await page.evaluate(title=>{const tag={id:'existing-long',title,assignable:true};window.noteHarness.tags=[tag];window.noteHarness.tagOptions=[tag]},existingLongName)
  await page.getByRole('button',{name:'Edit note tags',exact:true}).click()
  await page.getByLabel('Find note tags').fill(existingLongName)
  assert.equal(await page.getByRole('checkbox',{name:existingLongName,exact:true}).isChecked(),true,'Existing long tag names remain visible and selected')
  assert.equal(await page.getByText('Tag name is too long. Use a shorter name.',{exact:true}).count(),0,'An existing tag is not rejected as a new name')
  await page.getByLabel('Find note tags').fill('é'.repeat(33))
  await page.getByText('Tag name is too long. Use a shorter name.',{exact:true}).waitFor()
  assert.equal(await page.getByRole('button',{name:/^Create “/}).count(),0,'New names above 64 UTF-8 bytes cannot be created')
  await page.getByLabel('Find note tags').fill('é'.repeat(32))
  await page.getByRole('button',{name:`Create “${'é'.repeat(32)}”`,exact:true}).waitFor()
  await page.getByLabel('Find note tags').fill('a'.repeat(65))
  assert.equal(await page.getByRole('button',{name:/^Create “/}).count(),0)
  await page.getByRole('button',{name:'Cancel',exact:true}).click()
  checks.push('New note tags respect the native 64-byte UTF-8 limit while existing long tags stay visible and usable')

  await page.evaluate(()=>window.noteHarness.scene='editor')
  await page.getByLabel('Note title',{exact:true}).fill('Updated brief')
  assert.equal(await page.getByLabel('Note category',{exact:true}).count(),0)
  await page.getByRole('tab',{name:'Markdown',exact:true}).click()
  await page.getByLabel('Note content',{exact:true}).fill('# Updated\n\n- [ ] Review')
  await page.getByRole('button',{name:'Back to side panel',exact:true}).click()
  assert.equal(await page.evaluate(()=>window.noteHarness.collapsed),true)
  assert.deepEqual(await page.evaluate(()=>window.noteHarness.draft),{id:'one',title:'Updated brief',content:'# Updated\n\n- [ ] Review',category:'Research',etag:'v1'})
  await page.getByRole('button',{name:'Save note',exact:true}).click()
  assert.equal(await page.evaluate(()=>window.noteHarness.saved),true)
  checks.push('Expanded editor shares title, Markdown and version with its parent while displaying the folder read-only; returning to the sidebar preserves the draft')
  await page.evaluate(()=>window.noteHarness.scene='files')
  await page.getByRole('checkbox',{name:'Brief.pdf',exact:true}).check()
  await page.getByRole('button',{name:'Notes',exact:true}).click()
  await page.getByRole('checkbox',{name:'Reference.md',exact:true}).check()
  await page.getByRole('button',{name:'Attach 2 files',exact:true}).click()
  await page.getByRole('alert').waitFor()
  assert.deepEqual(await page.evaluate(()=>window.noteHarness.attached),['/Brief.pdf'])
  assert.equal(await page.getByRole('button',{name:'Remove Brief.pdf from selection',exact:true}).count(),0)
  assert.equal(await page.getByRole('button',{name:'Remove Reference.md from selection',exact:true}).count(),1)
  assert.equal(await page.evaluate(()=>window.noteHarness.fileDone),false)
  assert.equal(await page.evaluate(()=>window.noteHarness.fileBusy),false)
  await page.evaluate(()=>window.noteHarness.failFile=false)
  await page.getByRole('button',{name:'Attach 1 file',exact:true}).click()
  await page.waitForFunction(()=>window.noteHarness.fileDone)
  assert.deepEqual(await page.evaluate(()=>window.noteHarness.attached),['/Brief.pdf','/Notes/Reference.md'])
  assert.deepEqual(await page.evaluate(()=>window.noteHarness.attachCalls),['/Brief.pdf','/Notes/Reference.md','/Notes/Reference.md'])
  assert.equal(await page.evaluate(()=>window.noteHarness.fileChanges),2)
  checks.push('Files selection spans folders; native attachment partial failures retain only failed selections and retries do not reattach successful files')
  assert.deepEqual(errors,[])
  console.log(JSON.stringify({passed:checks.length,checks},null,2))
}finally{await browser.close()}
